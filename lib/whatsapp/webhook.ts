// §7.8: status updates, opt-outs and template review results from Meta.

const { campaignMessages, templates, whatsappIdentities } = schema;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

const sha256 = (text: string) => createHash('sha256').update(text).digest();

/** Hashed first, so the comparison takes the same time whatever the lengths are. */
export const safeEqual = (a: string, b: string) => timingSafeEqual(sha256(a), sha256(b));

/** `X-Hub-Signature-256`: an HMAC of the exact raw body, keyed with the App Secret. */
export function verifyMetaSignature(rawBody: string, header: string | null, appSecret: string): boolean {
  if (!header?.startsWith('sha256=')) return false;
  return safeEqual(header.slice('sha256='.length).toLowerCase(), createHmac('sha256', appSecret).update(rawBody).digest('hex'));
}

/** §5.2: generated by the app. Derived rather than stored, so showing it on S-01 doesn't need a write on a GET. */
export async function whatsappVerifyToken(db: Tx, env: Record<string, string | undefined> = process.env): Promise<string | null> {
  const chosen = await getSecret(db, 'WHATSAPP_WEBHOOK_VERIFY_TOKEN', env);
  if (chosen) return chosen;
  return env.APP_ENCRYPTION_KEY ? createHmac('sha256', env.APP_ENCRYPTION_KEY).update('whatsapp-webhook-verify-token').digest('base64url').slice(0, 32) : null;
}

type StatusEvent = {
  id?: string;
  status?: string;
  timestamp?: string;
  recipient_id?: string;
  recipient_user_id?: string;
  biz_opaque_callback_data?: string;
  errors?: GraphError[];
  pricing?: { category?: string };
};
type RawMessage = {
  type?: string;
  from?: string;
  from_user_id?: string;
  text?: { body?: string };
  button?: { payload?: string; text?: string };
  interactive?: { button_reply?: { title?: string } };
};
export type MetaPayload = {
  entry?: {
    changes?: {
      field?: string;
      value?: {
        statuses?: StatusEvent[];
        messages?: RawMessage[];
        contacts?: { wa_id?: string; user_id?: string }[];
        event?: string;
        message_template_id?: string | number;
        reason?: string;
      };
    }[];
  }[];
};

const INCOMING: Record<string, IncomingStatus> = { sent: 'sent', delivered: 'delivered', read: 'read', failed: 'failed' };
const e164 = (phone: string) => `+${phone.replace(/^\+/, '')}`;

/** Remembers which phone a BSUID belongs to. A STOP that arrived with no phone takes effect as soon as the phone is known. */
async function noteIdentity(tx: Tx, bsuid: string | undefined, phone: string | undefined, now: Date) {
  if (!bsuid) return;
  const phoneE164 = phone ? e164(phone) : null;
  const [row] = await tx
    .insert(whatsappIdentities)
    .values({ bsuid, phoneE164, firstSeenAt: now, lastSeenAt: now })
    .onConflictDoUpdate({ target: whatsappIdentities.bsuid, set: { phoneE164: sql`COALESCE(${phoneE164}, ${whatsappIdentities.phoneE164})`, lastSeenAt: now } })
    .returning();
  if (row?.suppressedAt && row.phoneE164) {
    await addSuppression(tx, { channel: 'whatsapp', identifier: row.phoneE164, reason: 'stop_keyword', source: row.suppressionSource, createdBy: 'system:webhook' });
  }
}

async function applyStatus(tx: Tx, event: StatusEvent, now: Date) {
  await noteIdentity(tx, event.recipient_user_id, event.recipient_id, now);
  const incoming = INCOMING[event.status ?? ''];
  if (!incoming) return; // §7.2.1: a status this version doesn't know about changes nothing.

  const callback = event.biz_opaque_callback_data;
  const byCallback = callback && UUID.test(callback) ? await tx.select().from(campaignMessages).where(eq(campaignMessages.id, callback)).for('update') : [];
  const [row] = byCallback.length || !event.id ? byCallback : await tx.select().from(campaignMessages).where(eq(campaignMessages.wamid, event.id)).limit(1).for('update');
  // Test sends have no row, so they end here.
  if (!row || row.channel !== 'whatsapp') return;

  const seconds = Number(event.timestamp);
  const at = Number.isFinite(seconds) && seconds > 0 ? new Date(seconds * 1000) : now;
  const result = reduceStatus(
    { status: row.status as MessageStatus, wamid: row.wamid, accepted_at: row.acceptedAt, sent_at: row.sentAt, delivered_at: row.deliveredAt, read_at: row.readAt, failed_at: row.failedAt },
    { status: incoming, at, wamid: event.id },
  );
  if (result.unmatched) return;

  const { patch } = result;
  const error = event.errors?.[0];
  const fields = result.runFailureAction && error ? failureFields(error) : null;
  await tx
    .update(campaignMessages)
    .set({
      updatedAt: now,
      ...(patch.status && { status: patch.status }),
      ...(patch.wamid && { wamid: patch.wamid }),
      ...(patch.sent_at && { sentAt: patch.sent_at }),
      ...(patch.delivered_at && { deliveredAt: patch.delivered_at }),
      ...(patch.read_at && { readAt: patch.read_at }),
      ...(patch.failed_at && { failedAt: patch.failed_at }),
      ...(event.pricing?.category && { priceCategory: event.pricing.category }),
      ...(fields && { errorCode: fields.error_code, errorSubcode: fields.error_subcode, errorTitle: fields.error_title, errorDetail: fields.error_detail ?? fields.error_title, fbtraceId: fields.fbtrace_id }),
    })
    .where(eq(campaignMessages.id, row.id));

  // §7.7: one classifier for both paths. Only once, so a repeated webhook can't repeat it.
  const reason = result.runFailureAction && error ? classifyError({ code: error.code }).suppression_reason : undefined;
  if (reason && row.phoneE164) {
    await addSuppression(tx, { channel: 'whatsapp', identifier: row.phoneE164, reason, source: row.campaignId, createdBy: 'system:webhook' });
    await writeAudit(tx, { id: 'system:webhook' }, 'whatsapp.suppressed', 'campaign_message', { entityId: row.id, channel: 'whatsapp', details: { reason } });
  }
}

async function applyInbound(tx: Tx, message: RawMessage, keywords: string[], now: Date) {
  const inbound: InboundMessage = {
    type: message.type ?? '',
    body: message.text?.body,
    payload: message.button?.payload,
    text: message.button?.text,
    button_reply_title: message.interactive?.button_reply?.title,
    from: message.from,
    from_user_id: message.from_user_id,
  };
  const known = message.from_user_id ? (await tx.select().from(whatsappIdentities).where(eq(whatsappIdentities.bsuid, message.from_user_id)))[0] : undefined;
  const decision = detectOptOut(inbound, { keywords, identityMapping: known?.phoneE164 && message.from_user_id ? { [message.from_user_id]: known.phoneE164 } : {} });
  if (!decision.suppress || !decision.reason) return;

  if (decision.phone) {
    await addSuppression(tx, { channel: 'whatsapp', identifier: decision.phone, reason: decision.reason, source: 'webhook', createdBy: 'system:webhook' });
  } else if (decision.bsuid) {
    await tx
      .insert(whatsappIdentities)
      .values({ bsuid: decision.bsuid, suppressedAt: now, suppressionSource: 'webhook', firstSeenAt: now, lastSeenAt: now })
      .onConflictDoUpdate({ target: whatsappIdentities.bsuid, set: { suppressedAt: now, suppressionSource: 'webhook', lastSeenAt: now } });
  }
  await writeAudit(tx, { id: 'system:webhook' }, 'whatsapp.opt_out', 'contact', { channel: 'whatsapp', details: { reason: decision.reason, phone_known: Boolean(decision.phone) } });
}

const TEMPLATE_STATUS = new Set(['APPROVED', 'REJECTED', 'PENDING', 'PAUSED', 'DISABLED', 'FLAGGED', 'IN_APPEAL', 'PENDING_DELETION', 'REINSTATED']);

export async function applyMetaPayload(tx: Tx, payload: MetaPayload, now = new Date()) {
  const { optOutKeywords } = await getSettingsSection(tx, 'data');
  for (const entry of payload.entry ?? []) {
    for (const { field, value } of entry.changes ?? []) {
      if (!value) continue;
      if (field === 'message_template_status_update') {
        const event = value.event?.toUpperCase() ?? '';
        if (value.message_template_id !== undefined && TEMPLATE_STATUS.has(event)) {
          const status = event === 'REINSTATED' ? 'APPROVED' : event;
          await tx.update(templates).set({ status, rejectedReason: event === 'REJECTED' ? (value.reason ?? null) : null }).where(eq(templates.metaTemplateId, String(value.message_template_id)));
        }
        continue;
      }
      if (field !== 'messages') continue;
      for (const contact of value.contacts ?? []) await noteIdentity(tx, contact.user_id, contact.wa_id, now);
      for (const status of value.statuses ?? []) await applyStatus(tx, status, now);
      for (const message of value.messages ?? []) await applyInbound(tx, message, optOutKeywords, now);
    }
  }
}
